//! Constants used in rCore for qemu

pub const CLOCK_FREQ: usize = 12500000;
pub const MEMORY_END: usize = 0x8800_0000;

pub const MMIO: &[(usize, usize)] = &[
    (0x0010_0000, 0x00_2000), // VIRT_TEST/RTC  in virt machine
];


// 2. MEMORY_END: usize = 0x8800_0000
// 含义：物理内存的结束地址，即内存空间从0x0000_0000（起始）到0x8800_0000（不含）可用，总容量为 0x8800_0000 = 2281701376 字节 ≈ 2.15 GB。
// 关键背景：
// 在嵌入式 / 内核开发中，内存空间分为两部分：
// 普通内存（RAM）：地址0x0000_0000 ~ MEMORY_END - 1，用于存储代码、数据、栈堆；
// MMIO 区域：地址>= MEMORY_END（或代码中单独定义的区间），用于映射硬件寄存器（如你定义的MMIO数组）。
// virt平台关联：QEMU 的virt虚拟 ARM 平台默认支持灵活的内存配置，0x8800_0000是常见的 “内存 - 外设” 地址分界（避免与 MMIO 地址冲突）。

// 3. MMIO: &[(usize, usize)] = &[(0x0010_0000, 0x00_2000)]
// MMIO 概念：内存映射 I/O（Memory-Mapped I/O） 是硬件与 CPU 交互的核心方式 —— 将硬件寄存器（如 “RTC 时间寄存器”“测试设备状态寄存器”）映射到普通内存地址空间，CPU 通过 “读写内存地址” 即可操作硬件（无需专门的 I/O 指令）。
// 当前定义解析：
// 数组元素格式：(基地址, 大小)，表示一个 MMIO 区域；
// 基地址0x0010_0000：该外设的寄存器起始地址；
// 大小0x00_2000（8192 字节）：该外设占用的地址空间（包含所有寄存器）；
// 注释说明：VIRT_TEST/RTC in virt machine，明确该区域对应 QEMU virt平台的两个常用虚拟外设：
// VIRT_TEST（测试设备）：地址0x00100000，用于简单的状态查询 / 中断测试（如 “写特定值触发中断”）；
// RTC（实时时钟）：部分virt配置中，RTC 寄存器也映射在0x00100000附近，用于获取当前时间（需结合具体寄存器偏移）。
